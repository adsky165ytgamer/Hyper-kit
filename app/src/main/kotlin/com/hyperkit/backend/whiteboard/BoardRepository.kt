package com.hyperkit.backend.whiteboard

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

/**
 * Backend Shelf → local board storage.
 * Traditional terminology → Repository (Data layer), file based.
 *
 * One file per board: `<dir>/<id>.hyperkit.json`, plus `<dir>/last_opened`
 * holding the id of the board to reopen on launch. Writes go to a temp file
 * and are renamed into place, so a crash mid-save never corrupts a board.
 * Everything runs on [Dispatchers.IO].
 */
class BoardRepository(private val dir: File) {

    suspend fun save(document: BoardDocument) = withContext(Dispatchers.IO) {
        dir.mkdirs()
        val target = fileFor(document.id)
        val temp = File(dir, "${document.id}.tmp")
        temp.writeText(document.toJson())
        if (!temp.renameTo(target)) {
            // renameTo can fail when the target exists on some filesystems.
            target.delete()
            check(temp.renameTo(target)) { "Could not write board ${document.id}" }
        }
        File(dir, LAST_OPENED).writeText(document.id)
    }

    suspend fun load(id: String): BoardDocument? = withContext(Dispatchers.IO) {
        val file = fileFor(id)
        if (!file.isFile) return@withContext null
        BoardDocument.fromJson(file.readText())
    }

    /** All readable boards, most recently saved first. */
    suspend fun list(): List<BoardDocument> = withContext(Dispatchers.IO) {
        dir.listFiles { f -> f.name.endsWith(SUFFIX) }
            .orEmpty()
            .mapNotNull { BoardDocument.fromJson(it.readText()) }
            .sortedByDescending { it.updatedAt }
    }

    suspend fun delete(id: String) = withContext(Dispatchers.IO) {
        fileFor(id).delete()
        val last = File(dir, LAST_OPENED)
        if (last.isFile && last.readText() == id) last.delete()
    }

    suspend fun lastOpenedId(): String? = withContext(Dispatchers.IO) {
        File(dir, LAST_OPENED).takeIf { it.isFile }?.readText()?.trim()?.ifEmpty { null }
    }

    suspend fun setLastOpened(id: String) = withContext(Dispatchers.IO) {
        dir.mkdirs()
        File(dir, LAST_OPENED).writeText(id)
    }

    // Ids are generated by HyperKit (timestamps); strip anything path-like defensively.
    private fun fileFor(id: String) = File(dir, id.filter { it.isLetterOrDigit() || it == '-' || it == '_' } + SUFFIX)

    private companion object {
        const val SUFFIX = ".hyperkit.json"
        const val LAST_OPENED = "last_opened"
    }
}
